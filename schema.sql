CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  category text NOT NULL CHECK (length(category) BETWEEN 1 AND 60),
  description text NOT NULL DEFAULT '',
  price numeric(10,2) NOT NULL CHECK (price > 0),
  image text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_token uuid NOT NULL UNIQUE,
  customer text NOT NULL,
  phone text NOT NULL,
  items jsonb NOT NULL,
  total numeric(10,2) NOT NULL CHECK (total >= 0),
  payment text NOT NULL,
  change_for numeric(10,2),
  fulfillment text NOT NULL CHECK (fulfillment IN ('Entrega', 'Retirada no balcão')),
  address text,
  notes text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'received' CHECK (status IN ('received','preparing','out_for_delivery','completed','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_created_at_idx ON orders (created_at DESC);
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status);

CREATE TABLE IF NOT EXISTS admin_login_attempts (
  ip_hash text PRIMARY KEY,
  attempts integer NOT NULL DEFAULT 0,
  window_started_at timestamptz NOT NULL DEFAULT now(),
  blocked_until timestamptz
);

